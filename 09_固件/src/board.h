/* ==========================================================================
 * M2+：串口屏（淘晶驰 USART HMI 3.5″ 480×320）—— USART3，PB10=TX / PB11=RX
 *
 * 设计口径（《固件设计-协议与引脚.md》§7）：固件**只做透传代理，不解释屏的协议**
 * —— 淘晶驰的指令集是它自己的方言，让上位机（AI）直接写最灵活，改界面完全不用动固件。
 *
 * ⚠️ **波特率必须与屏侧一致**：本屏（TJC4832T135_011R）实测出厂为 **9600**（固件默认也是 9600）。
 *    不一致时屏**完全不响应**（收到的全是乱码）—— 不报错、不显示、一个字节都不回，最难查。
 *    改波特率用 `LCDBAUD <n>`（运行时生效，不用重烧）。
 *    **判据：发垃圾指令 `LCD zzz`，屏回 `1A FF FF FF` 即波特率正确。**
 * ⚠️ 屏侧是 **8N1**：别照抄 USART1 那套 8E1！两边帧格式不同是本项目特有的坑。
 * ⚠️ 淘晶驰（Nextion 系）**每条指令必须以 FF FF FF 结尾**才会执行：
 *    `lcd_send_text()` 会自动补；`lcd_send_bytes()` 原样不补。
 * ⚠️ 屏要独立 5V 供电（预留 5V/1A）并与主控**共地**。
 * ========================================================================== */
void lcd_init(uint32_t baud);                            /* 传 0 → 用默认 115200 */
uint32_t lcd_baud(void);
uint32_t lcd_send_text(const char *text);                 /* 原样发 + 自动补 FF FF FF；返回实际发出的字节数 */
void lcd_send_bytes(const uint8_t *data, uint32_t len);   /* 原样发，不补 */
void lcd_poll(void);                                     /* 主循环里排空屏发回的字节 */
int  lcd_getbyte(void);                                  /* 无数据返回 -1 */
void lcd_pulldown(int enable);                           /* 诊断：PB11 切下拉输入，判"屏的 TX 有没有接着" */

