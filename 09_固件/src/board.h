/* ==========================================================================
 * M3：X/Y 步进脉冲发生器（**软件生成**，TIM4 定时中断 + 两轴相位累加）
 *
 * 为什么用软件而不是硬件 PWM：
 *   · 引脚表把 PUL 放在 **PA0 / PA5**，这两个脚不属于同一路定时器的通道，
 *     而 F103 一个定时器只能有一个频率 → 硬件 PWM 做不到"两轴各自不同速"；
 *   · 软件相位累加顺带解决**两轴联动**（按比例给速率 = 直线插补）。
 *   代价 = ISR 频率 × ISR 耗时；10kHz 中断在 8MHz 主频下约占 10~20% CPU。
 *   ⚠️ 所以 TIM4 **只在运动时开**（`step_jog` 里 CEN=1；两轴都停了自动 CEN=0）。
 *
 * 引脚（**共阴接法**：驱动器 PUL−/DIR−/ENA− 全部接 GND）：
 *   X：PUL=**PA0**  DIR=**PA1**  EN=**PA4**
 *   Y：PUL=**PA5**  DIR=**PA6**  EN=**PA7**
 *
 * ⚠️ `STEP_EN_ACTIVE_LOW`：EN 按**多数驱动器"低有效"**处理（拉低=使能=电机自锁）。
 *    若实测反了（发 `EN 1` 反而松开），把这个宏改成 0。
 * ⚠️ 本版**没有加减速**：起步即目标频率。42 步进空载一般能直起 ~1kHz，带载更低。
 *    先 `SPD 800` 试，能走再往上加；**听到"咔咔"顿响 = 丢步，立刻降速**。
 *    梯形加减速 + `MOVE <mm>` + 回零放 M3b。
 * ⚠️ DIR 建立时间：`step_jog` 里 DIR 先变、再空转约 1ms 才发脉冲（驱动器要求 ≥5µs）。
 * ========================================================================== */
#define STEP_AXIS_X 0
#define STEP_AXIS_Y 1
#define STEP_ISR_HZ 10000u      /* TIM4 中断频率；**最大步频 = 一半 = 5kHz**（一步=两个半周期） */
#define STEP_MAX_HZ 5000u
#define STEP_EN_ACTIVE_LOW 1

void step_init(void);
void step_enable(int on);
int  step_jog(int axis, int32_t steps, uint32_t hz);  /* 0=已启动；<0=拒绝（见 .c 注释） */
void step_stop(void);
uint8_t step_busy(void);
int32_t step_pos(int axis);
uint32_t step_rate_hz(void);
void step_set_rate(uint32_t hz);
/* 诊断（M3?）：中断次数 / 当前速率 / 剩余半周期 —— 判断"中断到底在不在跑" */
uint32_t step_ticks(void);
uint32_t step_rate_now(int axis);
uint32_t step_half_now(int axis);

/* ---- M3b 追加：梯形加减速 + 毫米换算 + 软限位 ----------------------------
 * 为什么必须要加减速：步进**不能瞬间起步到高速**（转子跟不上 → 丢步/啸叫/堵转）。
 * 做法 = 对称梯形：从 STEP_START_HZ 起，用 `ramp` 步线性升到目标频率，结束前对称降回来。
 *   · ramp 比"总步数一半"还大 → 自动退化成**三角形**（短距离也平稳）；
 *   · ramp=0 → 关加减速（等于 M3 老行为，可对照测试）。
 *
 * ⚠️ **MOVE 的 mm 换算依赖 SMM（步/mm）**，默认 80 = 3200 步/圈 ÷ 40mm/圈。
 *    换了同步轮/带、或改了细分，**必须 `SMM <新值>`**，否则"走 100mm"是假的。
 *    实测校法：`ZERO x` → `MOVE x 100` → 卡尺量真实位移 L → `SMM 新值 = 旧值 × 100 / L`。
 *
 * 软限位以**步**存（命令里用 mm 给，好记），`LIM x off` 关掉。
 * ⚠️ 软限位**替代不了回零/硬限位**：它只知道"相对当前零点"的位置，丢了步它也不知道。 */
#define STEP_START_HZ 200u          /* 起步频率（42 步进很安全） */
#define STEP_DEFAULT_RAMP 200u      /* 默认加速步数（200 步 ≈ 0.1s 升到目标速度） */
#define STEP_DEFAULT_SMM 80u        /* 默认 步/mm（3200÷40）；改机构/细分后必须重设 */

void step_set_ramp(uint32_t steps);
uint32_t step_ramp(void);
void step_set_smm(uint32_t steps_per_mm);
uint32_t step_smm(void);
int  step_move_mm(int axis, int32_t mm, uint32_t hz);   /* 返回码同 step_jog */
void step_zero(int axis);
void step_set_limit(int axis, int32_t min_mm, int32_t max_mm);
void step_clear_limit(int axis);
int  step_limit_on(int axis);
int32_t step_limit_min_mm(int axis);
int32_t step_limit_max_mm(int axis);

